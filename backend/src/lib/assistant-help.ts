export function answerAppHelp(query: string, category?: string): string | null {
  const normalized = normalize(query);
  const topic = helpTopics.find(({ pattern }) => pattern.test(normalized));
  if (topic) return topic.answer(category);
  if (/^(как|почему|зачем|что делать)/i.test(normalized)) {
    return 'Я помогу с поиском товаров, акций, организаций и маршрутов, подскажу про избранное, профиль, геолокацию и уведомления. Уточните, что именно интересует — например «как добавить в избранное» или «почему цена отличается».';
  }
  return null;
}
